# ──────────────────────────────────────────────────────────────── 대조·생성
def load_companies():
    d = json.load(open(COMPANIES, encoding='utf-8'))
    by_name = {}
    for c in d['companies']:
        by_name.setdefault(c['name'], []).append(c)
    return by_name, d


def load_ncs():
    d = json.load(open(TAXONOMY, encoding='utf-8'))
    names = set()
    for lv in ('sub', 'middle'):
        for n in d['ncs']['levels'][lv]:
            names.add(n['name'])
    for n in d['keco']['levels']['sub']:
        names.add(n['name'])
    return names, d


def load_wf_jobs():
    """직업 현실 리얼 필터가 실제로 들고 있는 직무 이름(KSCO 세분류)."""
    p = os.path.join(ROOT, 'work-filter', 'data', 'work-context.json')
    d = json.load(open(p, encoding='utf-8'))
    return {j.get('name') for j in d.get('jobs') or [] if j.get('name')}


def load_thermo_names():
    """산업 온도계가 실제로 들고 있는 산업 id → 이름."""
    p = os.path.join(ROOT, 'thermometer', 'data', 'industries.json')
    d = json.load(open(p, encoding='utf-8'))
    return {r.get('id'): r.get('name') for r in d.get('industries') or [] if r.get('id')}


def load_terms():
    """내담자 언어 번역기가 실제로 들고 있는 표제어·한글명·별칭."""
    p = os.path.join(ROOT, 'translator', 'data', 'terms.json')
    d = json.load(open(p, encoding='utf-8'))
    idx = {}
    for x in d.get('terms') or []:
        for n in [x.get('term'), x.get('ko')] + list(x.get('aka') or []):
            if n:
                idx.setdefault(n, x.get('term'))
    return idx


def pick_company(by_name, key):
    """이름으로 명함첩 기업을 찾는다. 같은 이름이 여럿이면 대기업 → 직원 많은 쪽."""
    if key not in by_name:
        return None
    cand = sorted(by_name[key], key=lambda c: (c.get('category') != '대기업', -(c.get('employees') or 0)))
    return cand[0]


